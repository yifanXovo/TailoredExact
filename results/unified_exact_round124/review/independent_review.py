def parse_instance(path):
    lines=path.read_text(encoding='utf-8').splitlines()
    n,m,q=re.match(r'(\d+)\s+(\d+)\s+(\[.*\])',lines[0]).groups()
    fields={k.strip():ast.literal_eval(v.strip()) for k,v in (line.split('=',1) for line in lines[1:] if '=' in line)}
    return int(n),int(m),ast.literal_eval(q),fields

