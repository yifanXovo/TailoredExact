def close(a, b, tolerance=2e-12):
    assert abs(a-b) <= tolerance, (a, b, tolerance)


def classify(candidate, control):
    # Implement the published experimental decision rule directly.
    c, r = candidate, control
    if c['certificate'] != r['certificate']:
        return ('WIN', False) if c['certificate'] else ('LOSS', True)
    if c['certificate']:
        dt = c['T_produce'] - r['T_produce']
        threshold = max(30, .1*r['T_produce'])
        label = 'LOSS' if dt >= threshold else 'WIN' if dt <= -threshold else 'TIE'
        return label, c['T_produce'] >= 2*r['T_produce'] and dt >= 120
    du = c['U'] - r['U']
    dg = (c['U']-c['L']) - (r['U']-r['L'])
    au, ag = max(.001,.01*abs(r['U'])), max(.001,.10*abs(r['U']-r['L']))
    benefit = du <= -au or dg <= -ag
    harm = du >= au or dg >= ag
    label = 'MIXED' if benefit and harm else 'WIN' if benefit else 'LOSS' if harm else 'TIE'
    severe = du >= max(.001,.05*abs(r['U'])) and dg >= max(.005,.25*abs(r['U']-r['L']))
    return label, severe


