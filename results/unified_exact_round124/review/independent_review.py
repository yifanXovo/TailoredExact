def rounded_cell(text, original):
    if float(text)==original:
        return
    printed=Decimal(text)
    unit=Decimal(10)**printed.as_tuple().exponent
    assert abs(printed-Decimal(str(original))) <= unit*Decimal('.501'), (text,original)

