def parse_linear(line):
    name,expr=line.split(':',1); lhs,sense,rhs=re.split(r'\s(<=|>=|=)\s',expr)
    tokens=lhs.split(); coeff={}; pos=0; sign=1
    while pos<len(tokens):
        item=tokens[pos]
        if item in ('+','-'): sign=1 if item=='+' else -1; pos+=1; continue
        if re.fullmatch(r'[A-Za-z_]\w*',item): coefficient=1; variable=item; pos+=1
        else: coefficient=float(item); variable=tokens[pos+1]; pos+=2
        coeff[variable]=coeff.get(variable,0)+sign*coefficient; sign=1
    return name.strip(),coeff,sense,float(rhs)

